#!/usr/bin/env node
// Generates every reference page of the Horizon docs site from one pinned commit.
//
//   node scripts/generate.mjs <commit-sha>
//
// Reads: the repo at <sha> (git show, never the working tree), sources/board.json,
// sources/figma.json, the deployed Storybook's index.json and the npm registry.
// Writes (overwriting): the home page, All components, one page per component,
// Tokens, Changelog, Roadmap, News, src/styles/horizon-tokens.css and the
// generated block of the sidebar in astro.config.mjs. Guides are never touched.
//
// Nothing here invents content: a section with no source gets a notice naming
// exactly what is missing.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const DOCS = path.join(ROOT, 'src/content/docs');

function die(msg) {
	console.error(`generate: ${msg}`);
	process.exit(1);
}

const shaArg = process.argv[2];
if (!shaArg) die('usage: node scripts/generate.mjs <commit-sha>');

// Run git from the repository root so pathspecs (src/..., package.json) mean the same thing everywhere.
const TOP = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: ROOT, encoding: 'utf8' }).trim();
const git = (...args) => execFileSync('git', args, { cwd: TOP, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const SHA = git('rev-parse', '--verify', `${shaArg}^{commit}`).trim();
const SHORT = SHA.slice(0, 7);
const show = (p, rev = SHA) => git('show', `${rev}:${p}`);
const has = (p, rev = SHA) => {
	try {
		git('cat-file', '-e', `${rev}:${p}`);
		return true;
	} catch {
		return false;
	}
};

