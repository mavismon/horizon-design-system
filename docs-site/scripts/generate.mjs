function parseComponent(row) {
	const name = row.name;
	const dir = `src/components/${name}`;
	for (const f of [`${name}.tsx`, `${name}.css`, `${name}.stories.tsx`])
		if (!has(`${dir}/${f}`)) die(`${dir}/${f} doesn't exist at ${SHORT}, but ${name} is Cleared on the board.`);
	const tsx = show(`${dir}/${name}.tsx`);
	const css = show(`${dir}/${name}.css`);
	const stories = show(`${dir}/${name}.stories.tsx`);
	const intentPath = `${dir}/${name}.intent.json`;
	const intent = has(intentPath) ? JSON.parse(show(intentPath)) : null;
	const tsxLines = tsx.split('\n');
	const lineOf = (re, from = 0) => {
		for (let i = from; i < tsxLines.length; i++) if (re.test(tsxLines[i])) return i + 1;
		return null;
	};

	// Union types.
	const unions = [];
	for (const m of tsx.matchAll(/export type (\w+)\s*=\s*([^;]+);/g)) {
		const values = [...m[2].matchAll(/"([^"]+)"/g)].map((x) => x[1]);
		// An alias that only joins other types (ButtonGroupProps = A | B) has no string values: not a value union.
		if (!values.length) continue;
		unions.push({ name: m[1], values, line: lineOf(new RegExp(`export type ${m[1]}\\b`)) });
	}
	// The union type a prop's declared type names or draws its literals from (Exclude<ButtonGroupType, "segmented"> and "segmented" both give ButtonGroupType).
	const unionOf = (type) => {
		const words = type.match(/\w+/g) ?? [];
		const byName = unions.find((u) => words.includes(u.name));
		if (byName) return byName;
		const lits = [...type.matchAll(/"([^"]+)"/g)].map((x) => x[1]);
		return lits.length ? unions.find((u) => lits.every((v) => u.values.includes(v))) ?? null : null;
	};

	// Props interface, with doc comments. When the code has no single NameProps interface but several interfaces for
	// one component (a discriminated union such as ButtonGroupProps = ButtonGroupActionProps | ButtonGroupSegmentedProps),
	// every interface is read, locally extended ones included, and each prop keeps the type, default and doc it has in each.
	const parseIface = (ifaceName) => {
		const m = tsx.match(new RegExp(`(?:export )?interface (${ifaceName})\\s*(?:extends\\s+([^{]+))?\\{([\\s\\S]*?)\\n\\}`));
		if (!m) return null;
		const startLine = lineOf(new RegExp(`interface ${ifaceName}\\b`));
		const out = [];
		let doc = null;
		let inDoc = false;
		let buf = [];
		for (const raw of m[3].split('\n')) {
			const l = raw.trim();
			if (l.startsWith('/**')) {
				inDoc = true;
				buf = [];
			}
			if (inDoc) {
				buf.push(l.replace(/^\/\*\*|\*\/$|^\*/g, '').trim());
				if (l.endsWith('*/')) {
					inDoc = false;
					doc = buf.filter(Boolean).join(' ');
				}
				continue;
			}
			const pm = l.match(/^(\w+)(\?)?:\s*([^;]+);/);
			if (pm) {
				out.push({ name: pm[1], optional: !!pm[2], type: pm[3].trim(), doc, line: lineOf(new RegExp(`^\\s*${pm[1]}\\??:`), startLine), iface: ifaceName });
				doc = null;
			}
		}
		return { name: ifaceName, extends: m[2]?.trim().replace(/\s+/g, ' ').replace(/<\s+/g, '<').replace(/,?\s*>$/, '>') || null, line: startLine, props: out };
	};
	const props = [];
	let propsExtends = null;
	let propsLine = null;
	let ifaces = [];
	let unionAlias = null;
	const single = parseIface(`${name}Props`);
	if (single) {
		ifaces = [single];
		propsExtends = single.extends;
		propsLine = single.line;
		props.push(...single.props);
	} else {
		// Interfaces named after the component that the exported props type unions together.
		const alias = tsx.match(new RegExp(`export type ${name}Props\\s*=\\s*([^;]+);`));
		const members = alias ? alias[1].split('|').map((x) => x.trim()).filter((x) => /^\w+$/.test(x)) : [];
		for (const mName of members) {
			const mi = parseIface(mName);
			if (!mi) continue;
			// Fold in locally declared base interfaces.
			const baseProps = (mi.extends ?? '').match(/\w+/g)?.filter((w) => new RegExp(`interface ${w}\\b`).test(tsx)).flatMap((w) => parseIface(w)?.props ?? []) ?? [];
			const own = new Set(mi.props.map((p) => p.name));
			ifaces.push({ ...mi, props: [...baseProps.filter((p) => !own.has(p.name)).map((p) => ({ ...p, iface: mi.name })), ...mi.props] });
		}
		// One row per prop name, in order of first appearance; each row keeps what each interface says.
		const rows = new Map();
		for (const i of ifaces) for (const p of i.props) rows.set(p.name, [...(rows.get(p.name) ?? []), p]);
		for (const [pname, list] of rows) {
			const first = list[0];
			const distinct = (f) => [...new Set(list.map(f))];
			props.push({
				name: pname,
				optional: list.every((p) => p.optional),
				type: distinct((p) => p.type).join(' | '),
				doc: first.doc,
				line: first.line,
				perIface: list.length > 1 && distinct((p) => `${p.type}\u0000${p.doc}`).length > 1 ? list : null,
				ifaceNames: list.map((p) => p.iface),
			});
		}
		propsLine = ifaces[0]?.line ?? null;
		// The shared local base the members extend, and what that base extends (native attributes pass through it).
		const baseName = ifaces.flatMap((i) => (i.extends ?? '').match(/\w+/g) ?? []).find((w) => new RegExp(`interface ${w}\\b`).test(tsx));
		const base = baseName ? parseIface(baseName) : null;
		propsExtends = base?.extends ?? null;
		unionAlias = alias ? { name: `${name}Props`, text: alias[1].replace(/\s+/g, ' ').trim(), line: lineOf(new RegExp(`export type ${name}Props\\b`)), members: ifaces.map((i) => i.name), baseName, baseLine: base?.line ?? null } : null;
	}
	// Defaults from the destructured signature, per function: the exported component, or the internal functions that take one of the props interfaces.
	const sigs = [...tsx.matchAll(/function (\w+)\(\{((?:(?!\bfunction\b)[\s\S])*?)\}\s*:\s*(\w+)\)/g)];
	const exportSig = tsx.match(new RegExp(`export function ${name}\\(\\{([\\s\\S]*?)\\}\\s*:`));
	const exportDefaults = {};
	if (exportSig) for (const m of exportSig[1].matchAll(/(\w+)\s*=\s*("(?:[^"\\]|\\.)*"|[^,\n]+)/g)) exportDefaults[m[1]] = m[2].trim();
	const defaultsBy = new Map();
	for (const s of sigs) {
		const d = {};
		for (const m of s[2].matchAll(/(\w+)\s*=\s*("(?:[^"\\]|\\.)*"|[^,\n]+)/g)) d[m[1]] = m[2].trim();
		defaultsBy.set(s[3], d);
	}
	for (const p of props) {
		if (p.ifaceNames) {
			const per = [...new Set(p.ifaceNames)].map((i) => ({ iface: i, value: defaultsBy.get(i)?.[p.name] ?? null }));
			p.defaultsPer = per;
			p.default = per.every((x) => x.value === per[0].value) ? per[0].value : null;
		} else p.default = defaultsBy.get(`${name}Props`)?.[p.name] ?? exportDefaults[p.name] ?? null;
	}

	// CSS: declarations with line numbers, and every token read.
	const cssLines = css.split('\n');
	// A custom property the stylesheet defines itself (--hz-progressbar-fill) is component-local, not a token.
	const ownProps = new Set([...css.matchAll(/^\s*(--[\w-]+)\s*:/gm)].map((m) => m[1]));
	const tokensRead = [...new Set([...css.matchAll(/var\((--[\w-]+)/g)].map((m) => m[1]))].filter((n) => !ownProps.has(n)).sort();
	function findDecl(selector, property) {
		let current = null;
		for (let i = 0; i < cssLines.length; i++) {
			const l = cssLines[i];
			const open = l.match(/^([^{]+)\{/);
			if (open) current = open[1];
			const sels = (current ?? '').split(',').map((s) => s.trim());
			// A rule may start on an earlier line (comma-separated selector list).
			if (!open && /,\s*$/.test(l)) current = null;
			if (current && sels.includes(selector)) {
				const d = l.match(new RegExp(`^\\s*${property}:\\s*([^;]+);`));
				if (d) return { line: i + 1, text: l.trim() };
			}
			if (l.includes('}')) current = null;
		}
		return null;
	}

	// Stories: which are variant-matrix rows, which are examples.
	const unionProp = props.find((p) => unions.some((u) => u.name === p.type)) ?? props.find((p) => unionOf(p.type));
	const storyDefs = [];
	const exportRe = /export const (\w+)\s*:\s*Story\s*=\s*\{/g;
	const starts = [...stories.matchAll(exportRe)];
	starts.forEach((m, i) => {
		const body = stories.slice(m.index, starts[i + 1]?.index ?? stories.length);
		const line = stories.slice(0, m.index).split('\n').length;
		const argVal = unionProp ? body.match(new RegExp(`${unionProp.name}:\\s*"([^"]+)"`)) : null;
		const boolProps = BOOLEAN_MATRIX[name] ?? [];
		const boolSet = boolProps.every((bp) => new RegExp(`\\b${bp}:\\s*(?:true|false)`).test(body));
		const isRow = !/render\s*:/.test(body) && (!!argVal || (boolProps.length > 0 && boolSet) || !!ROW_STORIES[name]?.test(m[1])) && (!ROW_STORIES[name] || ROW_STORIES[name].test(m[1]));
		// The value each union-typed prop is set to in this story's args (a two-property matrix needs both).
		const argValues = {};
		for (const p of props) {
			if (!unionOf(p.type)) continue;
			const v = body.match(new RegExp(`\\b${p.name}:\\s*"([^"]+)"`));
			if (v) argValues[p.name] = v[1];
		}
		for (const bp of boolProps) {
			const v = body.match(new RegExp(`\\b${bp}:\\s*(true|false)`));
			if (v) argValues[bp] = v[1];
		}
		storyDefs.push({ exportName: m[1], line, isRow, value: argVal?.[1] ?? null, argValues, body });
	});
	// Figma's combined `state`, mapped to native attributes in the stories' header comment (see NATIVE_STATE).
	const ns = NATIVE_STATE[name];
	const storyLines = stories.split('\n');
	const nsStart = ns ? storyLines.findIndex((l) => (ns.start ?? /combined `state` maps to the native props/).test(l)) : -1;
	let nativeState = null;
	if (ns && nsStart >= 0) {
		let nsEnd = nsStart;
		while (nsEnd < storyLines.length - 1 && !(ns.end ?? /\.\s*$/).test(storyLines[nsEnd])) nsEnd++;
		let nsText = storyLines.slice(nsStart, nsEnd + 1).map((l) => l.replace(/^\s*\/\/\s?/, '')).join(' ');
		if (ns.end) nsText = nsText.slice(0, nsText.search(ns.end) + nsText.match(ns.end)[0].length);
		nativeState = { property: ns.property, startLine: nsStart + 1, endLine: nsEnd + 1, text: nsText };
		for (const sd of storyDefs) if (sd.isRow) sd.nativeState = ns.of(sd.body);
	}
	const sbFor = sbEntries.filter((e) => e.importPath?.includes(`/${name}/${name}.stories`));
	for (const s of storyDefs) s.sb = sbFor.find((e) => e.exportName === s.exportName && e.type === 'story') ?? null;
	const sbDocs = sbFor.find((e) => e.type === 'docs') ?? null;

	// Git history of the component folder.
	const log = git('log', '--format=%H%x09%h%x09%ad%x09%s', '--date=short', SHA, '--', dir)
		.split('\n')
		.filter(Boolean)
		.map((l) => {
			const [hash, short, date, subject] = l.split('\t');
			return { hash, short, date, subject, version: versionOf(hash) };
		});
	const since = tags.find((tag) => has('src/index.ts', tag) && new RegExp(`export \\{[^}]*\\b${name}\\b`).test(show('src/index.ts', tag)));

	// Parts of its own (see PARTS): each file read at the SHA, with its state union, props and defaults, where Calendar imports and renders it, and whether the package root exports it.
	const parts = (PARTS[name] ?? []).map((pc) => {
		const file = `${dir}/${pc.code}.tsx`;
		if (!has(file)) die(`${file} doesn't exist at ${SHORT}, but ${name} renders ${pc.code}.`);
		const src = show(file);
		const L = src.split('\n');
		const lineIn = (re, from = 0) => {
			const i = L.findIndex((l, k) => k >= from && re.test(l));
			return i < 0 ? 0 : i + 1;
		};
		const um = src.match(new RegExp(`export type ${pc.union}\\s*=\\s*([^;]+);`));
		const values = um ? [...um[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]) : [];
		const ifaceLine = lineIn(new RegExp(`export interface ${pc.code}Props\\b`));
		const im = src.match(new RegExp(`export interface ${pc.code}Props[^{]*\\{([\\s\\S]*?)\\n\\}`));
		const sig = src.match(new RegExp(`export function ${pc.code}\\(\\{([\\s\\S]*?)\\}\\s*:`));
		const defaults = {};
		if (sig) for (const m of sig[1].matchAll(/(\w+)\s*=\s*("(?:[^"\\]|\\.)*"|[^,\n]+)/g)) defaults[m[1]] = m[2].trim();
		const pprops = [];
		let doc = null;
		for (const raw of (im?.[1] ?? '').split('\n')) {
			const l = raw.trim();
			const dm = l.match(/^\/\*\*\s*(.*?)\s*\*\/$/);
			if (dm) {
				doc = dm[1];
				continue;
			}
			const pm = l.match(/^(\w+)(\?)?:\s*([^;]+);/);
			if (pm) {
				pprops.push({ name: pm[1], type: pm[3].trim(), doc, default: defaults[pm[1]] ?? null, line: lineIn(new RegExp(`^\\s*${pm[1]}\\??:`), ifaceLine) });
				doc = null;
			}
		}
		const tl = tsx.split('\n');
		const importLine = tl.findIndex((l) => new RegExp(`^import \\{ ${pc.code} \\} from "\\./${pc.code}"`).test(l)) + 1;
		const renderLines = tl.map((l, i) => (new RegExp(`<${pc.code}\\b`).test(l) ? i + 1 : 0)).filter(Boolean);
		const noteLine = lineIn(/^\/\*\* Internal part of/);
		const exported = new RegExp(`\\b${pc.code}\\b`).test(indexTs);
		return { ...pc, file, src, values, unionLine: lineIn(new RegExp(`export type ${pc.union}\\b`)), ifaceLine, props: pprops, importLine, renderLines, noteLine, note: noteLine ? L[noteLine - 1].replace(/^\/\*\*\s*|\s*\*\/$/g, '') : null, exported };
	});

	return { parts, nativeState, row, name, dir, tsx, css, intent, intentPath, unions, unionOf, ifaces, unionAlias, props, propsExtends, propsLine, tokensRead, findDecl, storyDefs, sbDocs, log, since: since?.replace(/^v/, '') ?? null, unionProp };
}

