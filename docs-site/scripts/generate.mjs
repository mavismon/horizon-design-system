// Escape text for MDX prose and table cells.
const t = (s) =>
	String(s)
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/\{/g, '&#123;')
		.replace(/\}/g, '&#125;')
		.replace(/\|/g, '\\|');
// Inline code, safe in tables.
const c = (s) => '`' + String(s).replace(/\|/g, '\\|') + '`';
const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const notice = (s) => `<p class="hz-missing"><strong>Missing source.</strong> ${t(s)}</p>`;
const blob = (p, line) => `${cfg.repoUrl}/blob/${SHA}/${p}${line ? `#L${line}` : ''}`;
const tree = (p) => `${cfg.repoUrl}/tree/${SHA}/${p}`;
const commitUrl = (h) => `${cfg.repoUrl}/commit/${h}`;
const GEN = `{/* Generated by docs-site/scripts/generate.mjs from ${SHA}. Don't edit by hand: change the source or the script. */}`;

function write(rel, content) {
	const file = path.join(DOCS, rel);
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, content.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n');
	written.push(rel);
}
const written = [];

function frontmatter(obj) {
	const lines = ['---'];
	for (const [k, v] of Object.entries(obj)) {
		if (typeof v === 'string') lines.push(`${k}: ${JSON.stringify(v)}`);
		else lines.push(`${k}:\n${v.map((x) => '  ' + x).join('\n')}`);
	}
	lines.push('---');
	return lines.join('\n');
}

async function getJson(url) {
	const res = await fetch(url);
	if (res.status === 404) return null;
	if (!res.ok) die(`${url} answered ${res.status}`);
	return res.json();
}

