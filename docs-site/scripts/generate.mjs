// ---------- release review facts (for News and the Design tab) ----------

function reviewFacts(url) {
	const m = url?.match(/github\.com\/[^/]+\/[^/]+\/blob\/([0-9a-f]{40})\/(.+)$/);
	if (!m) return null;
	try {
		const md = show(m[2], m[1]);
		return {
			url,
			date: md.match(/\*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})/)?.[1] ?? null,
			verdict: md.match(/\*\*Verdict:\*\*\s*\*\*(\w+)\*\*/)?.[1] ?? null,
			sha: md.match(/\*\*Reviewed SHA:\*\*\s*`([0-9a-f]+)`/)?.[1] ?? null,
			warnings: (mdSection(md, '## Warnings (not blocking)') ?? '')
				.split('\n')
				.filter((l) => l.startsWith('- '))
				.map((l) => l.slice(2)),
			other: (mdSection(md, '## Other findings (outside the gates)') ?? '')
				.split('\n')
				.filter((l) => l.startsWith('- '))
				.map((l) => l.slice(2)),
		};
	} catch {
		return { url, date: null, verdict: null, sha: null, warnings: [], other: [] };
	}
}

// Rulings in decisions.md that name the component in their heading.
function rulingsFor(name) {
	if (!decisions) return [];
	const out = [];
	for (const m of decisions.matchAll(/^## (.+)$/gm)) {
		if (!new RegExp(`\\b${name}\\b`).test(m[1])) continue;
		const body = mdSection(decisions, `## ${m[1]}`);
		const rulingPara = body.match(/\*\*Ruling\.\*\*\s*([\s\S]*?)(?=\n\*\*[A-Z][^*]*\.\*\*|$)/)?.[1] ?? '';
		const sentence = rulingPara.split('\n')[0].trim().replace(/:$/, '.');
		const tableRows = rulingPara
			.split('\n')
			.filter((l) => /^\|/.test(l) && !/^\|\s*-/.test(l))
			.map((l) => l.split('|').slice(1, -1).map((x) => x.trim()));
		// Columns are found by their header, so a table with or without a Selector column reads right.
		const head = (tableRows[0] ?? []).map((h) => h.toLowerCase());
		const col = (n) => head.indexOf(n);
		const values = tableRows.slice(1).map((r) => ({ cells: r, value: r[col('value')] ?? r[0], property: r[col('property')] ?? r[1], selector: col('selector') >= 0 ? r[col('selector')] : null, lines: r[col('lines')] ?? r[2] }));
		out.push({ title: m[1], ruling: sentence || null, values, notRuled: body.match(/\*\*Not ruled\.\*\*\s*([^\n]+)/)?.[1] ?? null });
	}
	return out;
}

