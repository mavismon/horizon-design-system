// Figma's combined `state` property, where the code has no such prop: the stories map it to native attributes
// and say so in a header comment. The matrix grid is only drawn when that comment is there to quote, and each
// single-cell story gets its state from the native args it sets. `of` reads those args from the story's source.
const NATIVE_STATE = {
	Toggle: {
		property: 'state',
		of: (body) => `${/\bdisabled:\s*true/.test(body) ? 'disabled-' : ''}${/\b(?:defaultChecked|checked):\s*true/.test(body) ? 'on' : 'off'}`,
	},
	// Dropdown: Figma's state is behaviour in the code (open = defaultOpen / open, disabled = disabled), not a prop.
	// `start` and `end` find the sentence in the stories' header comment; the quote stops where `end` matches.
	Dropdown: {
		property: 'state',
		start: /Figma's `state` maps to behaviour, not a prop/,
		columnNote: 'the story that sets the matching props (`defaultOpen` for open, `disabled` for disabled, neither for closed)',
		end: /`disabled`\./,
		of: (body) => (/\bdisabled:\s*true/.test(body) ? 'disabled' : /\b(?:defaultOpen|open):\s*true/.test(body) ? 'open' : 'closed'),
	},
};

// Stories that are single matrix cells, where the args alone don't tell them from the examples (Dropdown: LabelHidden
// and LabelAndValue also set size). A component listed here has as rows only the stories whose export name matches.
// Calendar: Picker and Occupancy are the two cells of the type matrix; PickerTwoMonths, PickerUncontrolled and PickerControlled
// also set (or leave) type=picker but are examples, and the Day* and OccupancyDay* stories are the internal parts' state stories.
// Card: Listing and Stat are the two cells of the type matrix; the other stories turn the show* booleans on or off and are examples.
// Form: Section and Card are the two cells of the type matrix (Section leaves type unset, so it takes the code's default, "section");
// the other Section* and Card* stories turn the show* booleans off or set fields, and are examples.
const ROW_STORIES = { Dropdown: /^(Md|Sm)(Closed|Open|Disabled)$/, Calendar: /^(Picker|Occupancy)$/, Card: /^(Listing|Stat)$/, Form: /^(Section|Card)$/ };

