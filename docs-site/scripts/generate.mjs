#!/usr/bin/env node
// Generates every reference page of the Horizon docs site from one pinned commit.
//
//   node scripts/generate.mjs <commit-sha>
//
// Reads: the repo at <sha> (git show, never the working tree), sources/board.json,
// sources/figma.json, the deployed Storybook's index.json and the npm registry.
// Writes (overwriting): the home page, All components, one page per component,
// Tokens, Changelog, Roadmap, News, src/styles/horizon-tokens.css and the
// generated block of the sidebar in astro.config.mjs. Guides are never touched.
//
// Nothing here invents content: a section with no source gets a notice naming
// exactly what is missing.

