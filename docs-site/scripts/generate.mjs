	if (fig?.unboundValues?.length) {
		design.push(
			`Values on the Figma node that aren't bound to a variable, and what ${c(`${name}.css`)} at ${c(SHORT)} does with each.\n\n| Layer | Property | Figma value | In the code |\n|---|---|---|---|\n` +
				fig.unboundValues
					.map((u) => {
						const d = u.css ? cp.findDecl(u.css.selector, u.css.property) : null;
						// A value that lives in an asset, not in the stylesheet, names the file and says so.
						const inCode = !u.css ? (u.codeFile ? `${t(u.codeNote ?? 'In the asset')}: [${c(u.codeFile)}](${blob(u.codeFile)})` : t(u.codeNote ?? 'Not set in the stylesheet')) : d ? `[${c(d.text)}](${blob(`${cp.dir}/${name}.css`, d.line)})` : `No ${c(u.css.property)} on ${c(u.css.selector)}`;
						return `| ${t(u.layer)} | ${t(u.property)} | ${c(u.value)} | ${inCode} |`;
					})
					.join('\n'),
		);
	} else if (Array.isArray(fig?.unboundValues)) design.push(`The Figma read of ${name} found no values on the node that aren't bound to a variable.`);
	else design.push(notice(`No unbound-value read for ${name} in sources/figma.json.`));

	design.push('## Figma variables against the token build');
	if (fig?.boundVariables) {
		const rows = Object.entries(fig.boundVariables).map(([v, figVal]) => {
			const codeName = v.toLowerCase();
			const built = light.get(codeName);
			const same = built && (built.toLowerCase() === String(figVal).toLowerCase() || built === `${figVal}px`);
			return { v, figVal, codeName, built, same };
		});
		design.push(
			'| Figma variable | Figma value | Token in the build | Built light value | Agrees |\n|---|---|---|---|---|\n' +
				rows.map((r) => `| ${c(r.v)} | ${c(r.figVal)} | ${r.built ? c(r.codeName) : '*no such token*'} | ${r.built ? c(r.built) : '—'} | ${!r.built ? '**no token**' : r.same ? 'yes' : '**no**'} |`).join('\n'),
		);
		const diff = rows.filter((r) => r.built && !r.same && /^#/.test(r.figVal));
		const missing = rows.filter((r) => !r.built);
		if (missing.length) design.push(`${missing.map((r) => c(r.v)).join(', ')} ${missing.length > 1 ? 'are' : 'is'} bound in Figma but the token build has no token of that name.`);
		const diffRead = diff.filter((r) => cp.tokensRead.includes(r.codeName));
		// A token this stylesheet doesn't read may still be read by the stylesheet of a component it is built from (Composes).
		const composedCss = (cp.row.composes ?? []).filter((n) => has(`src/components/${n}/${n}.css`)).map((n) => ({ n, css: show(`src/components/${n}/${n}.css`) }));
		const viaOf = (tok) => composedCss.filter((x) => new RegExp(`var\\(${tok}\\b`).test(x.css)).map((x) => x.n);
		const unread = diff.filter((r) => !cp.tokensRead.includes(r.codeName));
		const diffVia = unread.filter((r) => viaOf(r.codeName).length);
		const diffUnread = unread.filter((r) => !viaOf(r.codeName).length);
		if (diffRead.length) design.push(`${diffRead.length} colour variable${diffRead.length > 1 ? 's' : ''} in Figma still hold${diffRead.length > 1 ? '' : 's'} a different value from the token build, so the design file and the shipped component render ${diffRead.map((r) => c(r.v)).join(', ')} differently.`);
		if (diffVia.length) {
			const by = [...new Set(diffVia.flatMap((r) => viaOf(r.codeName)))];
			design.push(`${diffVia.map((r) => c(r.v)).join(', ')} ${diffVia.length > 1 ? 'hold' : 'holds'} a different value in Figma from the token of the same name in the build. ${c(`${name}.css`)} doesn't read ${diffVia.length > 1 ? 'those tokens' : 'that token'}, but the stylesheet of ${by.length > 1 ? 'the components' : 'the component'} ${name} is built from does (${by.map((n) => `[${c(`${n}.css`)}](${blob(`src/components/${n}/${n}.css`)})`).join(', ')}), so the ${by.join(' and ')} rendered inside ${name} uses the build's value, not Figma's.`);
		}
		if (diffUnread.length) design.push(`${diffUnread.map((r) => c(r.v)).join(', ')} ${diffUnread.length > 1 ? 'hold' : 'holds'} a different value in Figma from the token of the same name in the build, but ${c(`${name}.css`)} doesn't read ${diffUnread.length > 1 ? 'those tokens' : 'that token'}, so this doesn't change how the shipped component renders.`);
	}

	design.push('## Design gaps recorded against it');
	const gaps = [];
	for (const r of rulingsFor(name))
		gaps.push(
			`- **${t(r.title)}** ([decisions.md](${blob('decisions.md')})). ${r.ruling ? t(plain(r.ruling)) : ''}` +
				(r.values.length ? ` Accepted values: ${r.values.map((v) => `${c(plain(v.value))} (${t(plain(v.property))}${v.selector ? `, ${c(plain(v.selector))}` : ''}, line${/,/.test(v.lines) ? 's' : ''} ${t(v.lines)})`).join('; ')}.` : '') +
				(r.notRuled ? ` *Not ruled:* ${t(plain(r.notRuled))}` : ''),
		);
	for (const w of review?.warnings ?? []) gaps.push(`- From the [release review](${review.url}): ${t(plain(w))}`);
	// A review that keeps its findings under "Findings outside the gates" (not "Other findings") is only read for warnings here; say so.
	const reviewMd = review?.url?.match(/\/blob\/([0-9a-f]{40})\/(.+)$/);
	const hasFindings = !!reviewMd && /^## Findings outside the gates/m.test(show(reviewMd[2], reviewMd[1]));
	for (const n of rn.design ?? []) design.push(n);
	if (!gaps.length && rn.design?.length) {
		// The design findings above are the gaps; nothing else is recorded.
	} else design.push(gaps.length ? gaps.join('\n') : hasFindings ? notice(`No design gaps are recorded against ${name} in decisions.md, and the warnings section of its release review lists none. The review's findings outside the gates are not carried onto this page, except the ones quoted on the Code tab; they stay in the [release review](${review.url}).`) : notice(`No design gaps are recorded against ${name} in decisions.md or its release review.`));

	// ----- Changelog -----
	const changelog = [];
	changelog.push(`Every commit to ${c(cp.dir)} up to ${c(SHORT)}, newest first, with the published version that carries it.`);
	changelog.push(
		'| Commit | Date | Version | Change |\n|---|---|---|---|\n' +
			cp.log.map((l) => `| [${c(l.short)}](${commitUrl(l.hash)}) | ${l.date} | ${l.version ? t(l.version) : '*Unreleased*'} | ${t(l.subject)} |`).join('\n'),
	);

	const tab = (label, body) => `<TabItem label="${label}">\n\n${body.join('\n\n')}\n\n</TabItem>`;
	return [
		frontmatter({ title: name, description: `${name}: when to use it, how to call it, what it was built from, and what has changed.` }),
		'',
		"import { Badge, Tabs, TabItem } from '@astrojs/starlight/components';",
		"import StoryFrame from '../../../../components/StoryFrame.astro';",
		"import FigmaFrame from '../../../../components/FigmaFrame.astro';",
		'',
		GEN,
		'',
		header,
		sinceNote,
		'',
		'<Tabs>',
		tab('Usage', usage),
		tab('Examples', examples),
		tab('Code', code),
		tab('Design', design),
		tab('Changelog', changelog),
		'</Tabs>',
	].join('\n');
