function readmeFirstParagraph() {
	if (!readme) return null;
	const body = readme.replace(/^#[^\n]*\n/, '').trim();
	return body.split(/\n\s*\n/)[0].trim();
}
function readmeSection(title) {
	if (!readme) return null;
	const m = readme.match(new RegExp(`^## ${title}\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, 'm'));
	return m ? m[1].trim() : null;
}
function mdSection(src, heading) {
	if (!src) return null;
	const lines = src.split('\n');
	const i = lines.findIndex((l) => l.trim() === heading);
	if (i < 0) return null;
	const level = heading.match(/^#+/)[0].length;
	const out = [];
	for (const l of lines.slice(i + 1)) {
		const h = l.match(/^(#+) /);
		if (h && h[1].length <= level) break;
		out.push(l);
	}
	return out.join('\n').trim();
}

// Tags reachable from SHA, oldest first.
